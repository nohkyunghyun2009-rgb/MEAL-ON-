///  앱에서 "숨길 가게" 목록
///  카카오 지도에는 있지만 우리 앱에 안 보여줄 곳 (문 닫은 곳, 식당이 아닌 곳, 제휴 안 할 곳 등)
///  여기 적힌 글자가 가게 이름에 들어 있으면 식당 탭·AI 추천 어디에도 안 나와요 (띄어쓰기 무시)
///  → 다시 보이게 하려면 그 줄을 지우면 돼요
/// ═══════════════════════════════════════════════════════════
class HiddenStores {
  static const List<String> names = [
    '냉면시대1987',
    '달곰스마카롱',
    '초원',
    '파리바게트 일산삼성점',
    '파리바게뜨 일산삼성점', // 카카오 표기가 다를 수 있어서 둘 다
    '목우촌웰빙마을 일산마두점',
    '얼음나라아이스크림할인점',
    '빠니스비떼',
    '크리스피파이 일산본점',
    '배스킨라빈스 일산백마점',
    '모노에',
    '낙원떡집',
    '꼴래말래',
    '뻥튀기 공작소',
    '뻥튀기공작소',
    '이자카야 아라이',
    '옛날통닭',
    '메이크어딜리버리',
  ];

  static String _norm(String s) => s.replaceAll(' ', '').toLowerCase();

  /// 이 가게 이름이 숨김 목록에 걸리는지
  static bool isHidden(String placeName) {
    final n = _norm(placeName);
    return names.any((h) => n.contains(_norm(h)));
  }
}
